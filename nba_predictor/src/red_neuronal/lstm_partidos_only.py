#Evalúa el modelo
def evaluate(loader):
    model.eval() #Modo evaluación, anula droput layers
    total_loss = 0.0
    all_probs, all_targets = [], [] #Guardamos todas las probabilidades y todos los targets
    with torch.no_grad():                       # quitamos el cálculo de gradientes
        for xb, yb in loader:
            xb = xb.to(device)                  #xb = [B,seq_len,input_size], yb = [0,1]
            yb = yb.to(device).float()          # MOvemos los tensroes al mismo dispositivo cpu o gpu
            logits = model(xb)                  # Pasamos el batch por el modelo
            loss = criterion(logits, yb)        #Calculamos pérdida
            total_loss += loss.item()           #Sumamos pérdida

            probs = torch.sigmoid(logits)       # [0,1] gracias a la función sigmoide
            all_probs.append(probs.detach().cpu())
            all_targets.append(yb.detach().cpu())
            #.detach() → separa del grafo de autograd, motor de PyTorch que calcula directamente gradiente,(ya no necesita gradientes).
            #.cpu() → mueve a CPU (por si el modelo está en GPU, para poder concatenar y usar numpy/metrics luego).
            #Guardas los resultados b

    probs = torch.cat(all_probs) #Concatenamos tensores
    targets = torch.cat(all_targets)
    pred_cls = (probs >= 0.5).float()  #Convertimos las probabilidades en clases, > 0.5 -> 1
    acc = (pred_cls == targets).float().mean().item() #Calcula la exactitud (accuracy) directamente con PyTorch: (pred_cls == targets) da un tensor de True/False., .float() → convierte a 1.0/0.0., .mean() → promedio de aciertos → proporción correcta., .item() → valor numérico.
    return total_loss/len(loader), acc # Pérdida promedio por batch

