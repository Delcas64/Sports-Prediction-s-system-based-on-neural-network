def split_by_team(df,feature_cols,seq_len, ratios=(0.7,0.15,0.15)):

  X_train, y_train = [], []
  X_val,   y_val   = [], []
  X_test, y_test = [],[]

  equipos = df['TEAM_ID'].unique() #Lista de equipos
  scalers = {}

  for equipo in equipos:
    df_equipo = df[df['TEAM_ID'] == equipo].sort_values('GAME_DATE')

    n = len(df_equipo) #Todas las filas del equipo
    n_train = int(ratios[0] * n)
    n_val   = int(ratios[1] * n)


    train_df = df_equipo.iloc[:n_train].copy() #Selecciono todas las filas hasta el 70%
    val_df   = df_equipo.iloc[n_train:n_train+n_val].copy() #Aqui desde el 70% hasta el 85%
    test_df  = df_equipo.iloc[n_train+n_val:].copy() #Y aqui desde el 85% hasta el final


    # 3. Entrenamos el escalador solo con los datos de entrenamiento del equipo
    scaler = StandardScaler(copy=True, with_mean=True, with_std=True)
    scalers[equipo] = scaler  # <-- Lo guardamos

    # 4. Aplicamos el mismo escalado a todo el bloque del equipo
    train_df[feature_cols] = np.nan_to_num(
    scaler.fit_transform(train_df[feature_cols]), nan=0.0, posinf=0.0, neginf=0.0)
    val_df[feature_cols] = np.nan_to_num(scaler.transform(val_df[feature_cols]), nan=0.0, posinf=0.0, neginf=0.0)
    test_df[feature_cols] = np.nan_to_num(scaler.transform(test_df[feature_cols]), nan=0.0, posinf=0.0, neginf=0.0)



    # 5. Creamos las secuencias para cada parte del mismo equipo
    X_train_aux, y_train_aux = build_team_sequences(train_df, seq_len, feature_cols)
    X_val_aux, y_val_aux = build_team_sequences(val_df, seq_len, feature_cols)
    X_test_aux, y_test_aux = build_team_sequences(test_df, seq_len, feature_cols)

    # 6. Las añadimos a las listas globales
    X_train.extend(X_train_aux); y_train.extend(y_train_aux)
    X_val.extend(X_val_aux);   y_val.extend(y_val_aux)
    X_test.extend(X_test_aux); y_test.extend(y_test_aux)

  # 7. Convertimos todo a arrays de numpy

  return (
    np.array(X_train, dtype=np.float32),
    np.array(y_train, dtype=np.float32),
    np.array(X_val, dtype=np.float32),
    np.array(y_val, dtype=np.float32),
    np.array(X_test, dtype=np.float32),
    np.array(y_test, dtype=np.float32),
    scalers
  )

