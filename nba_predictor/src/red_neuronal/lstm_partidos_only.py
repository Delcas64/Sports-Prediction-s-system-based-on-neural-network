HIDDEN_SIZE = 128
NUM_LAYERS = 2
DROPOUT = 0.5
LR = 5e-4
#Probar con mas num_layers y distintas hidden_size
class NBA_Predictor(nn.Module):
  #Dropout desactiva ciertas neuronas para mejorar el aprendizaje y forzar a que el
  #modelo no dependa de ciertas neuronas.
    def __init__(self, input_size, hidden_size=HIDDEN_SIZE, num_layers=NUM_LAYERS,dropout=DROPOUT):
        super().__init__()
        #batch_first=True, hace que el shape sea batch, seq,input_size
        self.lstm = nn.LSTM(input_size, hidden_size, num_layers,
                            batch_first=True, dropout=dropout)

        self.fc1 = nn.Linear(hidden_size, 64)
        self.relu1 = nn.ReLU()
        self.fc2 = nn.Linear(64, 16)
        self.relu2 = nn.ReLU()
        self.fc3 = nn.Linear(16, 1)

    def forward(self, x): #Método hacia delante , x tensor de secuencias para cada ejemplo hay seq_len timesteps y cada timestep tiene input_size features.
      out, _ = self.lstm(x) #out es el tensor con la salida en cada intervalo de tiempo, _ sería h_n, hidden final state y c_n, el de celda
      last = out[:, -1, :]          # última salida de la secuencia
      x = self.relu1(self.fc1(last))
      x = self.relu2(self.fc2(x))
      return self.fc3(x).squeeze(1) # Al pasar last por la capa lineal, self.fc, la última capa, squeeze elimina la dimensión 1, [B,1] 1 de hidden size

model = NBA_Predictor(input_size=input_size, hidden_size=HIDDEN_SIZE).to(device)

# Usamos BCEWithLogitsLoss porque el modelo devuelve logits, no aplicamos sigmoide
