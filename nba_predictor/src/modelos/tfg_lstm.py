class NBA_LSTM(nn.Module):
    def __init__(self,input_dim=INPUT_DIM, hidden_dim=HIDDEN_DIM, num_layers=NUM_LAYERS,dropout=DROPOUT):
        super().__init__()

        self.lstm = nn.LSTM(
            input_size=input_dim,
            hidden_size=hidden_dim,
            num_layers=num_layers,
            batch_first=True, # batch va primero: (batch, seq_len, feat)
            dropout=dropout
        )

        self.fc = nn.Linear(hidden_dim, 1)  # salida 1 -> prob de que gane el HOME



    #h_n → (num_layers, batch, hidden_dim) úlitmo estado oculto de la capa
    #c_n → igual pero para celda interna (solo LSTM).
    #out -> Representa la salida del LSTM en cada paso temporal.
    def forward(self, x):
        out, _ = self.lstm(x) # x: (batch, seq_len, input_dim)

        # Nos quedamos con la salida del último paso temporal
        last_hidden = out[:, -1, :]  # (batch, hidden_dim), El partido predicho tras ver la secuencia completa
        logits = self.fc(last_hidden) # (batch, 1)
        return logits # sin sigmoide, usaremos BCEWithLogitsLoss


