def train_model(model,train_loader):

  max_grad_norm = 5.0 #para el clipping
  EPOCHS = 20
  early_stop_patience = 5
  best_val_loss = float("inf")
  epochs_without_improvement = 0

  for epoch in range(1, EPOCHS + 1):
      model.train()
      running_loss = 0.0

      #Para las gráficas
      correct = 0
      total = 0

      #------------------------ENTRENAMIENTO---------------------------------
      for xb, yb in tqdm(train_loader, desc=f"Epoch {epoch}/{EPOCHS}"):
          xb, yb = xb.to(device), yb.to(device)  # (batch,1)

          optimizer.zero_grad()
          logits = model(xb)
          loss = criterion(logits, yb)
          loss.backward()

          #Gradientes y pesos para TensorBoard
          #for name, param in model.named_parameters():
          #  if param.grad is not None:
          #      writer.add_histogram(f"Gradients/{name}", param.grad, epoch)
          #      writer.add_histogram(f"Weights/{name}", param.data, epoch)

          # Gradient clipping (muy importante para LSTM)
          torch.nn.utils.clip_grad_norm_(model.parameters(), max_grad_norm)

          optimizer.step()

          # métricas de entrenamiento
          running_loss += loss.item() * xb.size(0)
          preds = (torch.sigmoid(logits) >= 0.5).float()
          correct += (preds == yb).float().sum().item()
          total += xb.size(0)


      # estadísticas de entrenamiento
      train_loss = running_loss / len(train_loader.dataset)
      train_acc = correct / total

      # ----------------------EVALUACION -------------------------------
      val_metrics = eval_model(model, val_loader)

      val_loss = val_metrics["loss"]
      val_acc = val_metrics["accuracy"]
      val_auc = val_metrics["auc"]
      val_f1 = val_metrics["f1"]

      scheduler.step(val_loss) #usamos el scheduler
      # guardar historial
      history["train_loss"].append(train_loss)
      history["val_loss"].append(val_loss)
      history["train_acc"].append(train_acc)
      history["val_acc"].append(val_acc)
      history["val_auc"].append(val_auc)
      history["val_f1"].append(val_f1)



      print(f"Epoch {epoch}/{EPOCHS} | "
            f"Train Loss: {train_loss:.4f} | Train Acc: {train_acc:.3f} | "
            f"Val Loss: {val_loss:.4f} | Val Acc: {val_acc:.3f}")

      #Métricas para TensorBoard

      writer.add_scalar("Loss/Train", train_loss, epoch)
      writer.add_scalar("Loss/Validation", val_loss, epoch)

      writer.add_scalar("Accuracy/Train", train_acc, epoch)
      writer.add_scalar("Accuracy/Validation", val_acc, epoch)


      # early stopping
      if val_loss < best_val_loss:
          best_val_loss = val_loss
          epochs_without_improvement = 0
          torch.save(model.state_dict(), PATH_LSTM)
          print("   → Mejor modelo guardado.")
      else:
          epochs_without_improvement += 1
          if epochs_without_improvement >= early_stop_patience:
              print("   → Early stopping activado.")
              break

