def eval_model(model, data_loader):
    model.eval() #Modo evaluación
    all_logits = []
    all_targets = []
    total_loss = 0.0

    with torch.no_grad(): #bucle sin gradientes
        for xb, yb in data_loader:
            xb, yb = xb.to(device), yb.to(device)

            logits = model(xb)
            loss = criterion(logits, yb)

            total_loss += loss.item() * xb.size(0)

            all_logits.append(logits.cpu())
            all_targets.append(yb.cpu())

    all_logits = torch.cat(all_logits)
    all_targets = torch.cat(all_targets)

    # SIGMOID → PROBABILIDADES
    probs = torch.sigmoid(all_logits) #probs > 0.5 -> 1
    preds = (probs >= 0.5).float()

    #Convertimos a numpy arrays
    t = all_targets.numpy().astype(int)
    p = preds.numpy().astype(int)
    pr = probs.numpy()


    #-------MÉTRICAS-----------
    acc = (p == t).mean()
    avg_loss = total_loss / len(data_loader.dataset)

    #El zero_division mejora warnings y posibles fallos
    f1 = f1_score(t, p, zero_division=0)
    precision = precision_score(t, p, zero_division=0)
    recall = recall_score(t, p, zero_division=0)
    auc = roc_auc_score(t, pr)

    return {
        "loss": avg_loss,
        "accuracy": acc,
        "f1": f1,
        "precision": precision,
        "recall": recall,
        "auc": auc,
        "targets": all_targets,
        "preds": preds,
        "probs": probs

    }

