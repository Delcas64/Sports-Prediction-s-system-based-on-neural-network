"""Debemos crear secuencias para la red. Para predecir X partido, coge Z partidos y con eso la red predice.

¿Qué hacemos? Para cada partido del dataset, cogemos los SEQ_LEN últimos partidos del local, cogemos los SEQ_LEN últimos del visitante, los juntamos y esta es la secuencia de entrada para la red.
"""

"""
NUEVO DATASET: para cada partido, obtenemos
- los últimos 10 partidos del HOME
- los últimos 10 partidos del AWAY
y los concatenamos → secuencia de 20 pasos.
"""

SEQ_LEN = 10  # partidos recientes de cada equipo

def ultimos_partidos_equipo(df, team_id, seq_len, current_date):
    """
    Devuelve los últimos seq_len partidos del equipo team_id
    ordenados por fecha. Si no llega a seq_len, hace padding
    con ceros al principio.
    """
    df_team = df[((df["TEAM_ID_HOME"] == team_id) | (df["TEAM_ID_AWAY"] == team_id))
    & (df["GAME_DATE"] < current_date)] #or bit a bit
    df_team = df_team.sort_values("GAME_DATE")

    feats = df_team[COLUMNAS].values.astype(np.float32)


    if len(feats) >= seq_len:
        return feats[-seq_len:]  # últimos seq_len partidos
    else: #Si un equpo no tiene 10 partidos, se rellena con ceros. Solo al principio
        pad = np.zeros((seq_len - len(feats), feats.shape[1]), dtype=np.float32)
        return np.vstack([pad, feats])  # padding arriba, es decir, los que más cerca están temporalmente, son de los que tenemos datos, si ocurre esta situación.


