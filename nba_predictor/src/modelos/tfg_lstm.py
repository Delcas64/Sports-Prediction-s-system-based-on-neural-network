"""Añadimos NET rating. Como no tenemos las posesiones, las estimamos.
En varios sitios coinciden que se pueden estimar así: sumando tiros libres + balones a la línea + pérdidas de balón - rebotes ofensivos. Los balones a la línea se estiman generalmente en 0,44*TBA.
Así que: Poss = FGA - OREB + TOV + 0.44 × FTA

Offensive Rating  = 100 × PTS / Poss

Defensive Rating  = 100 × PTS_recibidos / Poss_rival

Net Rating        = ORTG - DRTG

Función de calcular la posesión
"""

def estimate_possessions(df, prefix):
    return (
        df[f"FGA_{prefix}"]
        - df[f"OREB_{prefix}"]
        + df[f"TOV_{prefix}"]
        + 0.44 * df[f"FTA_{prefix}"]
    )

