def estimate_possessions(df, prefix):
    return (
        df[f"FGA_{prefix}"]
        - df[f"OREB_{prefix}"]
        + df[f"TOV_{prefix}"]
        + 0.44 * df[f"FTA_{prefix}"]
    )

df_temporadas["POSS_HOME"] = estimate_possessions(df_temporadas, "HOME")
df_temporadas["POSS_AWAY"] = estimate_possessions(df_temporadas, "AWAY")

